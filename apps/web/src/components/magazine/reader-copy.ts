const translations: Record<string, typeof en> = { en, ar, fr, es, pt, ru, zh, hi, bn, ur }

/** Only the reader controls are translated; the PDF language and page order stay intact. */
export function readerCopy(locale: string): typeof en {
  return Object.hasOwn(translations, locale) ? translations[locale]! : en
}
