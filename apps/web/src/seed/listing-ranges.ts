/**
 * Creates the "All Lebanon" issue and the seven governorate listing-number
 * ranges (19 November 2026), from the team's spreadsheet "All Lebanon listings
 * by region": 408 numbers in all.
 *
 *   pnpm exec tsx src/seed/listing-ranges.ts            shows what it would do
 *   pnpm exec tsx src/seed/listing-ranges.ts --apply    does it
 *
 * Guarded like the seed (it refuses any database but SEED_ALLOWED_DB) and safe
 * to re-run: an issue or range that already exists is left alone, and a range
 * that exists with different numbers is reported, never changed. Writes go
 * through Payload's local API, so the range rules (no overlap, inside the
 * issue total) run on every row.
 *
 * The issue needs a cover image and Payload requires one, so a new issue reuses
 * the cover of the newest existing issue until staff upload the real one.
 */

import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { config as loadEnv } from 'dotenv'
import { getPayload } from 'payload'
import { DEFAULT_LISTING_TOTAL, allocatedCount, nextFreeNumber } from '@vardenia/core'
import { assertSeedTarget } from './guard'

loadEnv({ path: path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../../.env') })

const { default: config } = await import('../payload.config')

const ISSUE_TITLE = 'All Lebanon'

const asData = <T>(data: Record<string, unknown>): T => data as T

/** The spreadsheet's "Regions" sheet, in its order. */
const RANGES = [
  { governorate: 'beirut', from: 1, to: 56 },
  { governorate: 'matn', from: 57, to: 116 },
  { governorate: 'keserwan', from: 117, to: 175 },
  { governorate: 'north-lebanon', from: 176, to: 234 },
  { governorate: 'beqaa', from: 235, to: 294 },
  { governorate: 'chouf', from: 295, to: 353 },
  { governorate: 'south-lebanon', from: 354, to: 408 },
] as const

async function main() {
  const apply = process.argv.includes('--apply')
  const target = assertSeedTarget()
  console.log(`${apply ? 'Applying to' : 'Dry run against'} ${target}`)

  // The sheet must itself be sound before anything is written.
  const total = DEFAULT_LISTING_TOTAL
  const sheetCount = allocatedCount(RANGES.map((r) => ({ ...r })))
  if (sheetCount !== total || nextFreeNumber(RANGES.map((r) => ({ ...r }))) !== total + 1) {
    throw new Error(`The ranges cover ${sheetCount} numbers, not ${total}. Nothing written.`)
  }

  const payload = await getPayload({ config })

  // 1. The issue.
  const found = await payload.find({
    collection: 'issues',
    where: { title: { equals: ISSUE_TITLE } },
    locale: 'en',
    depth: 0,
    limit: 1,
    overrideAccess: true,
  })
  let issueId: number | null = found.docs[0]?.id ?? null

  if (issueId) {
    console.log(`Issue "${ISSUE_TITLE}" exists (id ${issueId}).`)
  } else {
    const all = await payload.find({
      collection: 'issues',
      sort: '-issueNumber',
      depth: 0,
      limit: 1,
      overrideAccess: true,
    })
    const latest = all.docs[0]
    if (!latest)
      throw new Error('There is no issue to borrow a cover from. Create one in the admin.')
    const cover = typeof latest.cover === 'object' ? latest.cover.id : latest.cover
    const issueNumber = latest.issueNumber + 1
    console.log(
      `Would create issue "${ISSUE_TITLE}": number ${issueNumber}, total ${total}, cover borrowed from issue ${latest.issueNumber}.`,
    )
    if (apply) {
      const made = await payload.create({
        collection: 'issues',
        // The slug is generated by the collection, which the generated type
        // does not know; same cast as seed/run.ts.
        data: asData({
          title: ISSUE_TITLE,
          issueNumber,
          cover,
          publishedAt: new Date().toISOString(),
          listingTotal: total,
        }),
        locale: 'en',
        depth: 0,
        overrideAccess: true,
      })
      issueId = made.id
      console.log(`Created issue ${issueId}.`)
    }
  }

  // 2. The ranges.
  let created = 0
  for (const range of RANGES) {
    const existing = issueId
      ? await payload.find({
          collection: 'listing-ranges',
          where: {
            and: [{ issue: { equals: issueId } }, { governorate: { equals: range.governorate } }],
          },
          depth: 0,
          limit: 1,
          overrideAccess: true,
        })
      : { docs: [] }
    const have = existing.docs[0]
    if (have) {
      const same = have.from === range.from && have.to === range.to
      console.log(
        same
          ? `  ${range.governorate}: ${range.from}-${range.to} already there.`
          : `  ${range.governorate}: DIFFERENT range already there (${have.from}-${have.to}); left alone.`,
      )
      continue
    }
    console.log(
      `  ${range.governorate}: ${apply ? 'creating' : 'would create'} ${range.from}-${range.to}`,
    )
    if (apply && issueId) {
      await payload.create({
        collection: 'listing-ranges',
        data: { issue: issueId, governorate: range.governorate, from: range.from, to: range.to },
        depth: 0,
        overrideAccess: true,
      })
      created++
    }
  }

  console.log(
    apply
      ? `Done: ${created} range(s) created. ${sheetCount} of ${total} numbers allocated by the sheet.`
      : 'Dry run only. Run again with --apply to write.',
  )
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error)
    process.exit(1)
  })
