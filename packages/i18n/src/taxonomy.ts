/**
 * The label for a taxonomy slug in one of the extra UI languages, or undefined
 * when there is no override (English and Arabic, or a slug not listed). Callers
 * pass core's English as the fallback.
 */
export function taxonomyLabel(slug: string, locale: Locale): string | undefined {
  return TAXONOMY_LABELS[slug]?.[locale]
}

export function sectionLabel(path: string, locale: Locale): string | undefined {
  return SECTION_LABELS[path]?.[locale]
}

export function sectionDescription(path: string, locale: Locale): string | undefined {
  return SECTION_DESCRIPTIONS[path]?.[locale]
}
